// The manual's generated index — reading time and section headings, per page.
//
// Both are facts about a body's RENDERED text, so neither may be typed: a
// hand-written "6 min read" goes stale the first time the copy changes, and a
// hand-kept list of section titles for the search box is a second author of
// every heading. This renders each live body as the body tests do,
// derives both, and compares them with the committed module, the same shape as
// `contract:generate -- --check`: the artifact is committed so the gate has
// something to fail against.
//
//   npm run docs:index     rewrite src/components/docs/generated/docsIndex.generated.ts
//
// Reading time: rendered words / 200, rounded, at least 1. Prose, table cells
// and step text all count; inlined SVG figures do not (their labels are part of
// a picture, read at a glance). The body is rendered with no page context, so
// the header's own "N min read" never counts itself.

import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { StaticRouter } from "react-router-dom/server";
import { DOC_BODIES } from "../bodies";
import { ALL_PAGES } from "../registry";
import { DOCS_INDEX } from "../generated/docsIndex.generated";

const OUT = "src/components/docs/generated/docsIndex.generated.ts";

const text = (html: string) =>
  html
    .replace(/<svg[\s\S]*?<\/svg>/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&(?:amp|lt|gt|quot|#x27|#39|nbsp);/g, " ");

function build() {
  const index: Record<string, { minutes: number; sections: { id: string; title: string }[] }> = {};
  for (const page of ALL_PAGES) {
    const Body = DOC_BODIES[page.slug];
    if (page.status !== "live" || !Body) continue;
    const html = renderToStaticMarkup(
      createElement(StaticRouter, { location: `/docs/${page.slug}` }, createElement(Body)),
    );
    const words = text(html).split(/\s+/).filter(Boolean).length;
    const sections = [...html.matchAll(/<h2 id="([^"]+)"[^>]*>([\s\S]*?)<\/h2>/g)].map((m) => ({
      id: m[1],
      title: m[2]
        .replace(/<[^>]+>/g, "")
        .replace(/&#x27;|&#39;/g, "'")
        .replace(/&quot;/g, '"')
        .replace(/&amp;/g, "&")
        .replace(/\s+/g, " ")
        .trim(),
    }));
    index[page.slug] = { minutes: Math.max(1, Math.round(words / 200)), sections };
  }
  return index;
}

function serialise(index: ReturnType<typeof build>) {
  return [
    "// GENERATED by src/components/docs/__tests__/docsIndex.test.tsx — do not edit.",
    "// Regenerate with `npm run docs:index` after changing a page body.",
    "//",
    "// Per live page: reading time (rendered words / 200, at least 1) and its",
    "// `Section` headings in order — the page header, the troubleshooting jump",
    "// list and the search box's \"Inside pages\" all read it.",
    "",
    "export type DocsIndexEntry = { minutes: number; sections: { id: string; title: string }[] };",
    "",
    `export const DOCS_INDEX: Record<string, DocsIndexEntry> = ${JSON.stringify(index, null, 2)};`,
    "",
  ].join("\n");
}

describe("the generated docs index", () => {
  const index = build();

  it("matches the committed module — run `npm run docs:index` if this fails", () => {
    if (process.env.DOCS_INDEX_WRITE) writeFileSync(OUT, serialise(index));
    expect(readFileSync(OUT, "utf8")).toBe(serialise(index));
    expect(DOCS_INDEX).toBeDefined();
  });

  it("covers every live page and nothing else", () => {
    const live = ALL_PAGES.filter((p) => p.status === "live").map((p) => p.slug).sort();
    expect(Object.keys(index).sort()).toEqual(live);
  });

  it("finds no section id twice on one page — the id is the deep link", () => {
    for (const [slug, e] of Object.entries(index)) {
      const ids = e.sections.map((s) => s.id);
      expect(new Set(ids).size, `${slug} repeats a section id`).toBe(ids.length);
    }
  });
});
